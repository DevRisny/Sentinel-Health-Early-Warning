import ReactECharts from 'echarts-for-react'
import { CloudSun, Code2, Cpu, FileText, HeartPulse, Layers, Wind } from 'lucide-react'
import { useApp } from '../state'
import { Card, SyntheticTag } from '../ui'

const REPO = 'https://github.com/DevRisny/Sentinel-Health-Early-Warning'

const STEPS = [
  { icon: <CloudSun size={18} />, t: 'Real environment', d: 'Hourly temperature and dew point (ERA5) and PM10/PM2.5/dust (CAMS) for 5 Abu Dhabi districts, 2024 to Nov 2026, from Open-Meteo.' },
  { icon: <HeartPulse size={18} />, t: 'Health & workplace feeds', d: 'Daily heat-illness and respiratory visits, all-cause visits, sickness absence and incident reports for 12 site clusters. SYNTHETIC, from a documented generator.' },
  { icon: <Layers size={18} />, t: 'Expected values', d: 'Poisson seasonal baselines (season, weekday, Eid) per signal and site. Deviation z-scores and CUSUM measure what is unusual.' },
  { icon: <Cpu size={18} />, t: 'Fused risk model', d: 'Monotone-constrained LightGBM, one model per development season, averaged; Platt-calibrated probability of a burden surge in 48 h.' },
  { icon: <Wind size={18} />, t: 'Explain & act', d: 'SHAP contributions grouped by signal, fixed-template sentences, severity from an alert budget, and a proportionate action card.' },
]

export function DataMethod() {
  const { K, ds } = useApp()
  const gi = ds.trust.global_importance
  const fam: Record<string, string> = { environmental: '#e8780c', service: '#0e7c66', workplace: '#3e7cb1', context: '#a7b4c6' }
  const option = {
    grid: { left: 8, right: 30, top: 6, bottom: 6, containLabel: true },
    xAxis: { type: 'value', show: false },
    yAxis: { type: 'category', inverse: true, data: gi.map(g => g.group), axisLabel: { color: K.text, fontSize: 11 }, axisLine: { show: false }, axisTick: { show: false } },
    series: [{ type: 'bar', barWidth: 14, data: gi.map(g => ({ value: +g.mean_abs_shap.toFixed(3), itemStyle: { color: fam[g.family], borderRadius: 4 } })), label: { show: true, position: 'right', fontSize: 10, color: K.text } }],
  }
  return (
    <div className="grid gap-5">
      <Card title="How Sentinel works">
        <div className="grid gap-3 md:grid-cols-5">
          {STEPS.map((s, i) => (
            <div key={s.t} className="relative rounded-2xl border border-line bg-paper/60 p-4">
              <div className="mb-2 flex items-center gap-2"><span className="rounded-lg bg-white p-1.5 text-brand shadow-sm">{s.icon}</span><span className="text-xs font-bold text-ink-3">STEP {i + 1}</span></div>
              <div className="font-semibold text-ink">{s.t}</div>
              <p className="mt-1 text-[13px] leading-snug text-ink-2">{s.d}</p>
            </div>
          ))}
        </div>
      </Card>
      <div className="grid gap-5 xl:grid-cols-2">
        <Card title="Data sources and licences" pad={false}>
          <table className="w-full text-[13px]">
            <tbody className="divide-y divide-line">
              <tr><td className="px-5 py-3 font-semibold text-ink">Weather</td><td className="px-5 py-3 text-ink-2">{ds.meta.sources.weather} <span className="ml-1 rounded bg-brand-soft px-1.5 py-0.5 text-[11px] font-semibold text-brand">REAL</span></td></tr>
              <tr><td className="px-5 py-3 font-semibold text-ink">Air quality / dust</td><td className="px-5 py-3 text-ink-2">{ds.meta.sources.air_quality} <span className="ml-1 rounded bg-brand-soft px-1.5 py-0.5 text-[11px] font-semibold text-brand">REAL</span></td></tr>
              <tr><td className="px-5 py-3 font-semibold text-ink">Clinic, absence, incidents</td><td className="px-5 py-3 text-ink-2">Generated by <code>sentinel/simulate.py</code>, assumptions in DATA_SHEET.md <span className="ml-1"><SyntheticTag text="SYNTHETIC" /></span></td></tr>
              <tr><td className="px-5 py-3 font-semibold text-ink">Site clusters</td><td className="px-5 py-3 text-ink-2">12 illustrative clusters (construction, manufacturing, logistics, agriculture, energy). Names are places; sizes are simulated.</td></tr>
              <tr><td className="px-5 py-3 font-semibold text-ink">Policy context</td><td className="px-5 py-3 text-ink-2">UAE midday outdoor-work break (15 Jun to 15 Sep, 12:30 to 15:00) is modelled as reduced exposure.</td></tr>
            </tbody>
          </table>
        </Card>
        <Card title="What drives risk overall (mean |SHAP|, 2026)">
          <ReactECharts option={option} style={{ height: 300 }} notMerge />
          <div className="mt-1 flex flex-wrap gap-3 text-[11px] text-ink-2">
            {Object.entries(fam).map(([k, c]) => <span key={k} className="flex items-center gap-1"><span className="h-2 w-2 rounded-full" style={{ background: c }} />{k}</span>)}
          </div>
        </Card>
      </div>
      <Card title="Limitations we state plainly">
        <ul className="grid gap-2 text-sm text-ink-2 md:grid-cols-2">
          <li>• Health feeds are synthetic: results prove the method and workflow, not real-world accuracy. A pilot on real aggregated data is the next step.</li>
          <li>• The WBGT value is a temperature-and-humidity proxy that ignores sun and wind; it is used as a relative index, not a compliance reading.</li>
          <li>• Weather "forecasts" are reanalysis values plus realistic error, not archived operational forecasts.</li>
          <li>• Dust-driven respiratory surges were the hardest scenario type in the hold-out year.</li>
          <li>• The alert threshold was set on 2025; 2026 ran hotter, so alert workload rose. Thresholds should be reviewed each season.</li>
          <li>• Not a medical device. No diagnosis or individual risk scoring.</li>
        </ul>
        <div className="mt-4 flex flex-wrap gap-3">
          <a href={REPO} target="_blank" rel="noreferrer" className="flex items-center gap-2 rounded-lg bg-ink px-4 py-2 text-sm font-semibold text-[#fff] hover:opacity-90"><Code2 size={16} />Source code</a>
          <a href={`${REPO}/blob/main/docs/TECHNICAL_DOCUMENTATION.md`} target="_blank" rel="noreferrer" className="flex items-center gap-2 rounded-lg border border-line bg-white px-4 py-2 text-sm font-semibold text-ink hover:bg-paper"><FileText size={16} />Technical documentation</a>
        </div>
      </Card>
    </div>
  )
}
